object DomainLabels {
    fun label(raw: String?): String {
        val value = raw?.trim().orEmpty()
        if (value.isEmpty()) return "—"
        entityName(value)?.let { return it }
        val folded = fold(value)
        val aliased = ALIASES[folded] ?: ALIASES[value.lowercase()] ?: value
        val table = if (LocaleStore.locale == AppLocale.EN_US) EN else PT
        table[aliased]?.let { return it }
        table[aliased.uppercase()]?.let { return it }
        if (UUID_RE.matches(value)) return value.take(8)
        if (CODE_RE.matches(value)) {
            return humanize(value)
        }
        return value
    }

    private fun fold(value: String): String =
        java.text.Normalizer.normalize(value, java.text.Normalizer.Form.NFD)
            .replace(Regex("\\p{M}+"), "")
            .lowercase()

    private fun entityName(id: String): String? {
        val pair = FARMS[id] ?: FIELDS[id] ?: MACHINES[id] ?: return null
        return if (LocaleStore.locale == AppLocale.EN_US) pair.second else pair.first
    }

    private fun humanize(value: String): String {
        val words = value.split('_', '-').filter { it.isNotBlank() }.map { it.lowercase() }
        if (words.isEmpty()) return value
        return words.mapIndexed { i, w -> if (i == 0) w.replaceFirstChar { it.uppercase() } else w }.joinToString(" ")
    }

