const UUID_RE =
  /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i
const CODE_RE = /^[A-Z]{2,}(_[A-Z0-9]+)*$/

function stripAccents(value: string): string {
  return value.normalize('NFD').replace(/\p{M}/gu, '')
}

export function humanizeCode(value: string, locale: Locale): string {
  const words = value.split(/[_-]+/).filter(Boolean)
  if (words.length === 0) return value
  const lowered = words.map((w) => w.toLowerCase())
  if (locale === 'en-US') {
    return lowered.map((w, i) => (i === 0 ? w.charAt(0).toUpperCase() + w.slice(1) : w)).join(' ')
  }
  return lowered.map((w, i) => (i === 0 ? w.charAt(0).toUpperCase() + w.slice(1) : w)).join(' ')
}

export function domainLabel(locale: Locale, raw?: string | null): string {
  if (raw == null || String(raw).trim() === '') return '—'
  const value = String(raw).trim()

  const demoScout = value.match(/^(?:Observação demo|Observacao demo|DEMO_SCOUT)[ _#]*(\d+)$/i)
  if (demoScout) {
    return locale === 'en-US' ? `Demo scouting ${demoScout[1]}` : `Observação demo ${demoScout[1]}`
  }
  const demoEntry = value.match(/^(?:Lançamento demo|Lancamento demo|DEMO_ENTRY)[ _#]*(\d+)$/i)
  if (demoEntry) {
    return locale === 'en-US' ? `Demo entry ${demoEntry[1]}` : `Lançamento demo ${demoEntry[1]}`
  }
  const demoWindow = value.match(/^(?:Janela demo|DEMO_WINDOW)\s+(\w+)\s+#(\d+)$/i)
  if (demoWindow) {
    const type = domainLabel(locale, demoWindow[1])
    return locale === 'en-US'
      ? `Demo window ${type} #${demoWindow[2]}`
      : `Janela demo ${type} #${demoWindow[2]}`
  }
  const woTitle = value.match(
    /^(Troca de filtros|Revisão hidráulica|Calibração de GPS|Troca de óleo|Inspeção de bicos|Alinhamento|Substituição de correia|Diagnóstico motor|FILTER_CHANGE|HYDRAULIC_SERVICE|GPS_CALIBRATION|OIL_CHANGE|NOZZLE_INSPECTION|ALIGNMENT|BELT_REPLACEMENT|ENGINE_DIAGNOSTIC)\s+#(\d+)$/i,
  )
  if (woTitle) {
    return `${domainLabel(locale, woTitle[1])} #${woTitle[2]}`
  }

  const folded = stripAccents(value).toLowerCase()
  const aliased = ALIASES[folded] ?? ALIASES[value] ?? value
  const table = locale === 'en-US' ? EN : PT
  if (table[aliased]) return table[aliased]
  const upper = aliased.toUpperCase()
  if (table[upper]) return table[upper]
  if (table[value]) return table[value]

  if (UUID_RE.test(value)) {
    return value.slice(0, 8)
  }
  if (CODE_RE.test(value)) {
    return humanizeCode(value, locale)
  }
  return value
}

export function isUuid(value?: string | null): boolean {
  return Boolean(value && UUID_RE.test(value))
}
